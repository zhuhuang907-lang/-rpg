/** 给提示词：本朝官名小抄（只写最常用的几级） */
function eraOfficeBlock(y) {
  const Y = Number(y) || 0;
  if (!Y) return '';
  return `【本朝官名（写官职一律照此，不得混用别朝叫法）】县的主官称「${countyHead(Y)}」；州/郡/府的主官称「${prefHead(Y)}」，副贰称「${prefDeputy(Y)}」。`
    + (Y < 960 ? '本朝没有「知县」「知州」「知府」「通判」这些官名。' : '')
    + (Y >= 1368 ? '本朝没有「刺史」「太守」「县令」这些正式官名（文人口头雅称除外，正文与官文书里不用）。' : '')
    + '官员只能在本政权此时实际控制的地方任职；京城的县、府另有其制，不要随手写成普通县。';
}

