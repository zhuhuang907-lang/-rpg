function powersOf(role, idm) {
  const r = String(role || '');
  // 一人兼数职（「都督诸军事、安西将军、益州刺史」）：把相符的几类职权合起来，最多三类
  const hits = POWERS.filter(([re]) => re.test(r)).slice(0, 3);
  if (hits.length) return [...new Set(hits.flatMap(([, list]) => list))];
  if (idm === 'emperor') return POWERS[0][1];
  if (idm === 'commoner') return ['自家的营生、田产与家务', '没有公权：遇事只能求告、具状、托人'];
  return [];
}

