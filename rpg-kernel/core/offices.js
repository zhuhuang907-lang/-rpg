/**
 * 历代地方官名与职权（粗表，只收最常见的几级，用来防止「唐朝的知县」「明朝的刺史」这类时代错置）。
 * 年份为公元纪年（前 221 写 -221）。
 *
 *   countyHead(y)  县的主官叫什么        prefHead(y) 州/郡/府的主官
 *   fixTitle(s, y) 把一段官名里明显不合时代的词换成当时的叫法（只改官名，不改人名地名）
 *   eraOfficeBlock(y) 给提示词用的「本朝官名」小抄
 *   powersOf(role, idm) 按官名推出大致职权（用于个人面板与提示词）
 */

function countyHead(y) {
  if (y < 960) return '县令';
  if (y < 1279) return '知县';
  if (y < 1368) return '县尹';
  return '知县';
}
function prefHead(y) {
  if (y < 220) return '郡太守';
  if (y < 589) return '刺史';            // 魏晋南北朝：州刺史（郡另有太守）
  if (y >= 742 && y <= 757) return '太守'; // 唐天宝元年改州为郡、刺史为太守，至德二载复旧
  if (y < 960) return '刺史';
  if (y < 1279) return '知州';
  if (y < 1368) return '路总管';
  return '知府';
}
function prefDeputy(y) {
  if (y < 220) return '郡丞';
  if (y < 589) return '别驾、长史';    // 魏晋南北朝：州有别驾、长史、司马；郡有郡丞
  if (y < 960) return '州司马';
  if (y < 1279) return '通判';
  if (y < 1368) return '同知';
  return '同知';
}

/* 明显的时代错置：[正则, 年份范围外即错, 替换函数] */
const RULES = [
  // 知县：宋以后才有
  { future: true, re: /知县/g, bad: y => y < 960, to: y => countyHead(y) },
  { re: /知县/g, bad: y => y >= 1279 && y < 1368, to: () => '县尹' },
  // 县令作为正式官名：明清称知县
  { re: /县令/g, bad: y => y >= 1368, to: () => '知县' },
  // 知州、知府：宋以后
  { future: true, re: /知州/g, bad: y => y < 960, to: y => prefHead(y) },
  { future: true, re: /知府/g, bad: y => y < 960, to: y => (y < 589 ? '太守' : '府尹') },
  // 通判：宋才设
  { future: true, re: /通判/g, bad: y => y < 960, to: y => prefDeputy(y) },
  // 刺史、太守：明清没有这两个正式官名
  { re: /刺史/g, bad: y => y >= 1368, to: () => '知州' },
  { re: /太守/g, bad: y => y >= 1368, to: () => '知府' },
  // 巡抚、总督、布政使：明以后（宋有安抚使）
  { future: true, re: /巡抚/g, bad: y => y < 1368, to: y => (y >= 960 ? '安抚使' : '刺史') },
  { future: true, re: /布政使/g, bad: y => y < 1368, to: y => (y >= 960 ? '转运使' : '刺史') },
  // 节度使：唐睿宗以后、宋初还有，元明清没有
  { re: /节度使/g, bad: y => y < 710 || y >= 1279, to: y => (y < 710 ? '都督' : '总兵') },
];

/** 把官名里明显不合时代的词换成当时叫法；返回 { text, changed: [[旧,新]] } */
function fixTitle(s, y, { futureOnly = false } = {}) {
  let text = String(s || '');
  const Y = Number(y) || 0;
  const changed = [];
  if (!Y || !text) return { text, changed };
  for (const r of RULES) {
    if (!r.bad(Y)) continue;
    // 正文里只改「那时还没有的官名」；旧官名在对话里提起前朝旧事是可能的，不动
    if (futureOnly && !r.future) continue;
    text = text.replace(r.re, m => { const n = r.to(Y); if (n !== m) changed.push([m, n]); return n; });
  }
  return { text, changed };
}

