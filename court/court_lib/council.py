"""政事堂议事：三方独立调查 → 交换奏议 → 相互质疑 → 第二轮回应 → 皇帝裁决 → 写奏章待御批。
默认最多两轮正式辩论；分歧照实记录，不许虚构一致（第十二章第三条）。"""
import json
