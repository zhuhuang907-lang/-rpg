def pack(pid, title, y0, y1):
    rulers = []
    for pol, dys, L in R:
        eras = sorted([(n, a, b) for dy, n, a, b in NH if dy in dys and not (pol == '唐' and dy == 77 and (a > 690 or n in ('天授',))) and not (pol == '武周' and n == '载初')], key=lambda x: x[1])
        for name, title2, a, b in L:
            if b < y0 or a > y1: continue
            mine = []
            for n, ea, eb in eras:
                # 年号的起年落在谁的在位年里就是谁的；交接那年，归当年新即位的人
                owners = [x for x in L if x[2] <= ea <= x[3]]
                if not owners: continue
                own = max(owners, key=lambda x: x[2])
                if (pol, n) in OWN: own = next((x for x in owners if x[0] == OWN[(pol, n)]), next((x for x in L if x[0] == OWN[(pol, n)] and x[2] <= ea <= x[3] + 1), own))
                if own[0] == name and own[2] == a: mine.append([n, ea])
            rulers.append({'polity': pol, 'name': name, 'title': title2, 'reigns': mine, 'from': a, 'to': b})
    for pol, L in OTHER:
        for name, title2, a, b in L:
            if b < y0 or a > y1: continue
            rulers.append({'polity': pol, 'name': name, 'title': title2, 'reigns': [], 'from': a, 'to': b})
    pols = list(dict.fromkeys(r['polity'] for r in rulers))
    out = {'id': pid, 'title': title, 'range': [y0, y1], 'rulersOnly': True, 'source': '君主在位照正史；年号照哈佛库（CBDB）年号表', 'polities': pols, 'rulers': rulers, 'events': [], 'figures': []}
    json.dump(out, open(ROOT / 'web' / 'history' / f'{pid}.json', 'w', encoding='utf8'), ensure_ascii=False, indent=1)
    print(pid, len(rulers), '位君主', sum(len(r['reigns']) for r in rulers), '个年号')
